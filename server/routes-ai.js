function staffRow(userId) {
  return db
    .prepare('SELECT id, role, is_founder, permissions, status FROM users WHERE id = ?')
    .get(userId);
}

function isStaff(row) {
  if (!row) return false;
  if (Number(row.is_founder) === 1) return true;
  return ['moderator', 'admin', 'founder'].includes(String(row.role || ''));
}

/** Re-checked against the database on every request, never trusted from the session alone. */
function requireStaff(req, res, next) {
  const row = staffRow(req.user.id);
  if (!isStaff(row)) {
    return res.status(403).json({
      error: 'forbidden',
      message: 'This action needs a moderator or administrator.',
    });
  }
  req.staff = row;
  return next();
}

