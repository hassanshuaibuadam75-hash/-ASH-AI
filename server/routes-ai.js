function dailyUsage(userId) {
  const since = new Date(Date.now() - 86400000).toISOString();
  return db
    .prepare('SELECT COUNT(*) AS n FROM ai_usage WHERE user_id = ? AND created_at >= ?')
    .get(userId, since).n;
}

function recordUsage(userId, feature, ok) {
  try {
    insertRow('ai_usage', {
      id: uid('aiu_'),
      user_id: userId,
      feature,
      ok: ok ? 1 : 0,
      created_at: now(),
    });
  } catch {
    /* usage accounting must never fail a request */
  }
}

