router.post(
  '/ai/chat',
  requireAuth,
  rateLimit({ name: 'ai_chat', limit: 60, windowMs: 60 * 60 * 1000 }),
  async (req, res) => {
    const raw = Array.isArray(req.body.messages) ? req.body.messages : [];
    if (!raw.length) return badRequest(res, 'Send at least one message.');
    if (raw.length > 20) return badRequest(res, 'Keep each request to 20 messages or fewer.');

    const messages = [];
    let totalChars = 0;
    for (const entry of raw) {
      const role = entry && entry.role === 'assistant' ? 'assistant' : 'user';
      const content = clean(entry && entry.content, 4000);
      if (!content) continue;
      totalChars += content.length;
      messages.push({ role, content });
    }
    if (!messages.length) return badRequest(res, 'Send at least one message.');
    if (totalChars > 12000) return badRequest(res, 'That conversation is too long. Start a new chat.');

    if (dailyUsage(req.user.id) >= DAILY_LIMIT) {
      return res
        .status(429)
        .json({ error: 'ai_daily_limit', message: 'Daily #ash AI limit reached. Try again tomorrow.' });
    }
    if (!groqConfigured()) {
      return res
        .status(503)
        .json({ error: 'ai_not_configured', message: FRIENDLY_ERRORS.not_configured, kind: 'not_configured' });
    }

    try {
      const result = await groqChat({
        messages: [{ role: 'system', content: systemPrompt(clean(req.body.surface, 40)) }, ...messages],
        temperature: 0.6,
        maxTokens: 900,
      });
      recordUsage(req.user.id, 'chat', true);
      return res.json({
        reply: result.text,
        model: result.model,
        provider: 'groq',
        usage: result.usage,
        disclosure: AI_DISCLOSURE,
      });
    } catch (err) {
      recordUsage(req.user.id, 'chat', false);
      return res.status(err.status || 502).json(groqErrorBody(err));
    }
  }
);

