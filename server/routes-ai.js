const columnCache = new Map();

function tableColumns(table) {
  if (!columnCache.has(table)) {
    const rows = db.prepare(`PRAGMA table_info(${table})`).all();
    columnCache.set(table, new Set(rows.map((c) => c.name)));
  }
  return columnCache.get(table);
}

/** Insert only the columns this database actually has, so schema drift cannot break us. */
function insertRow(table, values) {
  const columns = tableColumns(table);
  const entries = Object.entries(values).filter(([key]) => columns.has(key));
  if (!entries.length) throw new Error(`No known columns for ${table}`);
  const sql = `INSERT INTO ${table} (${entries.map(([k]) => k).join(', ')}) VALUES (${entries
    .map(() => '?')
    .join(', ')})`;
  db.prepare(sql).run(...entries.map(([, value]) => value));
  return values.id;
}

