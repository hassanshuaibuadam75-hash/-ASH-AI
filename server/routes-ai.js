router.post(
  '/ai/actions',
  requireAuth,
  rateLimit({ name: 'ai_action', limit: 60, windowMs: 60 * 60 * 1000 }),
  (req, res) => {
    const type = clean(req.body.type, 20);
    const clientId = clean(req.body.clientId, 80) || null;
    const asAiAccount = req.body.asAiAccount === true;
    const approved = req.body.approved === true;

    if (!['post', 'comment', 'like', 'share'].includes(type)) {
      return badRequest(res, 'Unknown AI action.');
    }
    if (!approved) {
      return res.status(400).json({
        error: 'approval_required',
        message: '#ash AI cannot post, comment, like or share on your behalf without your explicit approval.',
      });
    }

    // Idempotency: a replayed queued action returns the original result, never a duplicate.
    if (clientId) {
      const seen = db
        .prepare('SELECT * FROM ai_actions WHERE user_id = ? AND client_id = ?')
        .get(req.user.id, clientId);
      if (seen) {
        return res.json({
          deduped: true,
          action: seen.type,
          postId: seen.result_id,
          message: 'This action was already applied.',
        });
      }
    }

    if (asAiAccount && !isStaff(staffRow(req.user.id))) {
      return res.status(403).json({
        error: 'forbidden',
        message: 'Only moderators and administrators may publish through the official #ash AI account.',
      });
    }

    const authorId = asAiAccount ? aiAccount.id : req.user.id;
    const audience = ['public', 'friends', 'private'].includes(clean(req.body.audience, 20))
      ? clean(req.body.audience, 20)
      : 'public';

    if (type === 'post' || type === 'share') {
      const body = clean(req.body.body, 5000);
      const targetPostId = clean(req.body.postId, 80);

      if (type === 'share') {
        const target = livePost(targetPostId);
        if (!target) return res.status(404).json({ error: 'not_found', message: 'That post no longer exists.' });
      } else if (!body) {
        return badRequest(res, 'A post needs some text.');
      }

      const postId = uid('p_');
      const ts = now();
      insertRow('posts', {
        id: postId,
        author_id: authorId,
        body: type === 'share' ? body : body,
        kind: type === 'share' ? 'share' : 'text',
        audience,
        shared_post_id: type === 'share' ? targetPostId : null,
        client_id: clientId,
        ai_generated: 1,
        created_at: ts,
        updated_at: ts,
      });
      auditAction(req.user.id, type, type === 'share' ? targetPostId : postId, clientId, postId, asAiAccount);

      return res.status(201).json({
        action: type,
        post: {
          id: postId,
          body: type === 'share' ? body : body,
          audience,
          aiGenerated: true,
          author: publicAuthor(authorId),
        },
        disclosure: asAiAccount
          ? 'Published by the official #ash AI account.'
          : 'AI-assisted post. You approved publishing it.',
      });
    }

    if (type === 'comment') {
      const postId = clean(req.body.postId, 80);
      const body = clean(req.body.body, 2000);
      const target = livePost(postId);
      if (!target) return res.status(404).json({ error: 'not_found', message: 'That post no longer exists.' });
      if (!body) return badRequest(res, 'A comment needs some text.');

      const commentId = uid('c_');
      insertRow('comments', {
        id: commentId,
        post_id: postId,
        author_id: authorId,
        body,
        ai_generated: 1,
        created_at: now(),
      });
      auditAction(req.user.id, 'comment', postId, clientId, commentId, asAiAccount);

      return res.status(201).json({
        action: 'comment',
        comment: { id: commentId, postId, body, aiGenerated: true, author: publicAuthor(authorId) },
        disclosure: asAiAccount
          ? 'Comment posted by the official #ash AI account.'
          : 'AI-assisted comment. You approved it.',
      });
    }

    // like
    const postId = clean(req.body.postId, 80);
    const target = livePost(postId);
    if (!target) return res.status(404).json({ error: 'not_found', message: 'That post no longer exists.' });

    const existing = db
      .prepare('SELECT 1 AS n FROM post_likes WHERE post_id = ? AND user_id = ?')
      .get(postId, authorId);
    if (existing) {
      auditAction(req.user.id, 'like', postId, clientId, postId, asAiAccount);
      return res.json({ action: 'like', postId, deduped: true, message: 'Already liked.' });
    }

    insertRow('post_likes', { id: uid('pl_'), post_id: postId, user_id: authorId, created_at: now() });
    auditAction(req.user.id, 'like', postId, clientId, postId, asAiAccount);
    return res.status(201).json({ action: 'like', postId, liked: true });
  }
);

