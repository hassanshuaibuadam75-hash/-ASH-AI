// #ash Mesh — data durability.
//
// One SQLite database (DATA_DIR/ash-mesh.db, WAL) plus DATA_DIR/uploads hold every record
// and every uploaded file. This module provides:
//
//   1. consistent snapshots          — `VACUUM INTO`, never a file copy of a live WAL database
//   2. verification                  — PRAGMA integrity_check + sha256 recorded in a sidecar
//   3. retention                     — newest N snapshots kept, older ones pruned
//   4. a Founder-only restore        — table-level, inside one transaction, always preceded by
//                                      a pre-restore safety snapshot
//   5. an off-platform archive       — one ZIP with the snapshot + uploads, because the Free
//                                      hosting plan has no persistent disk: anything that only
//                                      lives inside the container is lost on redeploy.
//
// A snapshot is never treated as valid until it has been opened again and passed an
// integrity check, and a restore is never reported as successful until the post-restore
// integrity and foreign-key checks pass.
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import zlib from 'node:zlib';
import crypto from 'node:crypto';
import Database from 'better-sqlite3';
import { db, DATA_DIR, UPLOAD_DIR, now, audit } from './db.js';
import { ensureFounderAccount } from './lib.js';

function clampInt(value, min, max, fallback) {
  const n = Number.parseInt(value, 10);
  if (Number.isNaN(n)) return fallback;
  return Math.min(max, Math.max(min, n));
}

function httpError(status, message) {
  const err = new Error(message);
  err.status = status;
  return err;
}

export const BACKUP_DIR = path.resolve(process.env.BACKUP_DIR || path.join(DATA_DIR, 'backups'));
export const BACKUP_RETENTION = clampInt(process.env.BACKUP_RETENTION, 2, 60, 14);
export const BACKUP_INTERVAL_MINUTES = clampInt(process.env.BACKUP_INTERVAL_MINUTES, 5, 24 * 60, 360);
export const BACKUP_SCHEDULER_ENABLED = String(process.env.BACKUP_SCHEDULER || '').toLowerCase() !== 'off';
// First automatic snapshot after boot, then every BACKUP_INTERVAL_MINUTES.
export const BACKUP_INITIAL_DELAY_MS = clampInt(process.env.BACKUP_INITIAL_DELAY_MS, 500, 60000, 15000);

// Snapshot names are generated by this module only; anything else is refused, which is what
// keeps a crafted name from reaching outside BACKUP_DIR.
const NAME_RE = /^ash-mesh-\d{8}-\d{6}-[0-9a-f]{6}\.db$/;

// Archive restore limits. A ZIP is untrusted input: entry count, per-file and total sizes are
// capped so a crafted archive cannot exhaust memory or fill the container.
const ARCHIVE_FORMAT = 'ash-mesh-export/2';
const ARCHIVE_MAX_ENTRIES = 20000;
const ARCHIVE_MAX_FILE_BYTES = clampInt(process.env.ARCHIVE_MAX_FILE_BYTES, 1024, 512 * 1024 * 1024, 256 * 1024 * 1024);
const ARCHIVE_MAX_TOTAL_BYTES = clampInt(process.env.ARCHIVE_MAX_TOTAL_BYTES, 1024, 2 * 1024 * 1024 * 1024, 1024 * 1024 * 1024);
const ARCHIVE_MAX_INFLATE_BYTES = 64 * 1024 * 1024;
// Uploaded media is written by lib.js as `<timestamp>-<24 hex>.bin`; a restore only ever
// accepts a bare name in this shape, so an archive cannot address a path.
const UPLOAD_NAME_RE = /^[A-Za-z0-9][A-Za-z0-9._-]{0,180}$/;

function safeUploadName(name) {
  if (typeof name !== 'string' || !name || name.length > 200) return null;
  if (name !== path.basename(name)) return null;
  if (name.startsWith('.') || name.includes('/') || name.includes('\\') || name.includes('\u0000')) return null;
  if (!UPLOAD_NAME_RE.test(name)) return null;
  return name;
}

/* ------------------------------- inspection ------------------------------- */

function tableNames(database) {
  return database
    .prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name")
    .all()
    .map((r) => r.name);
}

function quoteIdent(name) {
  return `"${String(name).replace(/"/g, '""')}"`;
}

/** Open a database file read-only and prove it is a healthy #ash Mesh database. */
export function inspectDatabaseFile(file) {
  const handle = new Database(file, { readonly: true, fileMustExist: true });
  try {
    const integrity = handle.pragma('integrity_check', { simple: true });
    const tables = tableNames(handle);
    const counts = {};
    let rows = 0;
    for (const table of tables) {
      const count = handle.prepare(`SELECT COUNT(*) AS c FROM ${quoteIdent(table)}`).get().c;
      counts[table] = count;
      rows += count;
    }
    return {
      integrity: String(integrity),
      tables,
      counts,
      rows,
      sqliteVersion: handle.prepare('SELECT sqlite_version() AS v').get().v,
    };
  } finally {
    handle.close();
  }
}

function sha256File(file) {
  const hash = crypto.createHash('sha256');
  const fd = fs.openSync(file, 'r');
  try {
    const buffer = Buffer.alloc(1024 * 1024);
    let read = 0;
    while ((read = fs.readSync(fd, buffer, 0, buffer.length, null)) > 0) hash.update(buffer.subarray(0, read));
  } finally {
    fs.closeSync(fd);
  }
  return hash.digest('hex');
}

/* -------------------------------- snapshots ------------------------------- */

function stamp(date = new Date()) {
  const p = (n, w = 2) => String(n).padStart(w, '0');
  return (
    `${date.getUTCFullYear()}${p(date.getUTCMonth() + 1)}${p(date.getUTCDate())}` +
    `-${p(date.getUTCHours())}${p(date.getUTCMinutes())}${p(date.getUTCSeconds())}`
  );
}

function uniqueName() {
  for (let attempt = 0; attempt < 20; attempt += 1) {
    const name = `ash-mesh-${stamp()}-${crypto.randomBytes(3).toString('hex')}.db`;
    if (!fs.existsSync(path.join(BACKUP_DIR, name))) return name;
  }
  throw new Error('Could not allocate a unique backup name.');
}

function sidecarPath(name) {
  return path.join(BACKUP_DIR, `${name}.json`);
}

/**
 * Create one verified snapshot. Throws if the snapshot cannot be written or does not pass
 * an integrity check — a failed backup must never look like a successful one.
 */
export function createBackup({ reason = 'manual', actorId = null } = {}) {
  fs.mkdirSync(BACKUP_DIR, { recursive: true });
  const name = uniqueName();
  const target = path.join(BACKUP_DIR, name);

  // VACUUM INTO writes a consistent copy of a live WAL database; a plain file copy can miss
  // committed pages that still live in the -wal file.
  db.prepare('VACUUM INTO ?').run(target);
  return finalizeSnapshot(name, { reason, actorId });
}

/** Re-open a written snapshot, prove it is healthy, record its checksum and apply retention. */
function finalizeSnapshot(name, { reason, actorId }) {
  const target = path.join(BACKUP_DIR, name);
  let inspection;
  try {
    inspection = inspectDatabaseFile(target);
  } catch (err) {
    fs.rmSync(target, { force: true });
    throw httpError(500, `The snapshot could not be verified: ${err.message}`);
  }
  if (inspection.integrity !== 'ok') {
    fs.rmSync(target, { force: true });
    throw httpError(500, 'The snapshot failed its integrity check and was discarded.');
  }

  const meta = {
    name,
    reason,
    actorId: actorId || null,
    createdAt: now(),
    sha256: sha256File(target),
    sizeBytes: fs.statSync(target).size,
    tableCount: inspection.tables.length,
    rows: inspection.rows,
    counts: inspection.counts,
    integrity: inspection.integrity,
    sqliteVersion: inspection.sqliteVersion,
  };
  fs.writeFileSync(sidecarPath(name), JSON.stringify(meta, null, 2));
  const pruned = pruneBackups();
  audit(actorId, 'backup.create', 'backup', name, { reason, sha256: meta.sha256, sizeBytes: meta.sizeBytes, rows: meta.rows }, '');
  return { ...meta, pruned };
}

export function listBackups() {
  if (!fs.existsSync(BACKUP_DIR)) return [];
  return fs
    .readdirSync(BACKUP_DIR)
    .filter((name) => NAME_RE.test(name))
    .map((name) => {
      const file = path.join(BACKUP_DIR, name);
      const stat = fs.statSync(file);
      let meta = null;
      try {
        meta = JSON.parse(fs.readFileSync(sidecarPath(name), 'utf8'));
      } catch {
        meta = null;
      }
      return {
        name,
        sizeBytes: stat.size,
        createdAt: meta?.createdAt || stat.mtime.toISOString(),
        reason: meta?.reason || 'unknown',
        sha256: meta?.sha256 || null,
        rows: meta?.rows ?? null,
        tableCount: meta?.tableCount ?? null,
        integrity: meta?.integrity || null,
      };
    })
    .sort((a, b) => (a.createdAt < b.createdAt ? 1 : -1));
}

/** Keep the newest BACKUP_RETENTION snapshots; remove older snapshot + sidecar pairs. */
export function pruneBackups() {
  const backups = listBackups();
  const removed = [];
  for (const backup of backups.slice(BACKUP_RETENTION)) {
    fs.rmSync(path.join(BACKUP_DIR, backup.name), { force: true });
    fs.rmSync(sidecarPath(backup.name), { force: true });
    removed.push(backup.name);
  }
  return removed;
}

export function resolveBackupPath(name) {
  if (typeof name !== 'string' || !NAME_RE.test(name)) {
    throw httpError(400, 'That is not a valid #ash Mesh backup name.');
  }
  const resolved = path.resolve(BACKUP_DIR, name);
  if (path.dirname(resolved) !== BACKUP_DIR) throw httpError(400, 'That backup path is not allowed.');
  if (!fs.existsSync(resolved)) throw httpError(404, 'That backup no longer exists.');
  return resolved;
}

/**
 * Adopt an uploaded .db file as a stored snapshot. The file is untrusted input: its SQLite
 * header is checked, then it is re-opened and must pass an integrity check before it can be
 * used as a restore source.
 */
export function adoptUploadedBackup(tempPath, { actorId = null } = {}) {
  if (!tempPath || !fs.existsSync(tempPath)) throw httpError(400, 'No database file was received.');

  const fd = fs.openSync(tempPath, 'r');
  const head = Buffer.alloc(16);
  try {
    fs.readSync(fd, head, 0, 16, 0);
  } finally {
    fs.closeSync(fd);
  }
  if (head.toString('latin1') !== 'SQLite format 3\u0000') {
    throw httpError(400, 'That file is not a SQLite database.');
  }

  fs.mkdirSync(BACKUP_DIR, { recursive: true });
  const name = uniqueName();
  const target = path.join(BACKUP_DIR, name);
  fs.copyFileSync(tempPath, target);

  try {
    const inspection = inspectDatabaseFile(target);
    if (inspection.integrity !== 'ok' || !inspection.tables.includes('users')) {
      fs.rmSync(target, { force: true });
      throw httpError(400, 'That database is not a healthy #ash Mesh backup.');
    }
  } catch (err) {
    fs.rmSync(target, { force: true });
    if (err.status) throw err;
    throw httpError(400, `That database could not be read: ${err.message}`);
  }

  return finalizeSnapshot(name, { reason: 'uploaded', actorId });
}

/** Re-verify a stored snapshot: integrity check, schema, and sidecar checksum match. */
export function verifyBackup(name) {
  const file = resolveBackupPath(name);
  const inspection = inspectDatabaseFile(file);
  let recorded = null;
  try {
    recorded = JSON.parse(fs.readFileSync(sidecarPath(name), 'utf8'));
  } catch {
    recorded = null;
  }
  const actualSha = sha256File(file);
  const checksumMatches = recorded?.sha256 ? recorded.sha256 === actualSha : null;
  return {
    name,
    ok: inspection.integrity === 'ok' && inspection.tables.includes('users') && checksumMatches !== false,
    integrity: inspection.integrity,
    hasUsersTable: inspection.tables.includes('users'),
    checksumMatches,
    sha256: actualSha,
    tableCount: inspection.tables.length,
    rows: inspection.rows,
    counts: inspection.counts,
  };
}

/* --------------------------------- restore -------------------------------- */

/**
 * Restore a snapshot over the live database.
 *
 * The live connection is a module singleton that every router closes over, so it cannot be
 * swapped for a new file handle. Instead every table present in both the snapshot and the
 * live schema is emptied and refilled inside a single transaction: a failure rolls back and
 * leaves the current data untouched. A pre-restore safety snapshot is always taken first.
 */
export function restoreBackup(name, { actorId = null, sessionId = null, ip = '', source = 'stored' } = {}) {
  const file = resolveBackupPath(name);
  const inspection = inspectDatabaseFile(file);
  if (inspection.integrity !== 'ok') {
    throw httpError(400, 'That backup failed its integrity check, so it was not restored.');
  }
  if (!inspection.tables.includes('users')) {
    throw httpError(400, 'That file is not an #ash Mesh database (no accounts table).');
  }

  // Copy the snapshot out of the backup directory before taking the safety snapshot:
  // createBackup() applies retention, and the snapshot being restored must never be the
  // file that retention prunes out from under the restore.
  const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), 'ash-restore-'));
  const tempSource = path.join(tempDir, 'source.db');
  fs.copyFileSync(file, tempSource);

  const safety = createBackup({ reason: 'pre-restore', actorId });
  const sessionRow = sessionId ? db.prepare('SELECT * FROM sessions WHERE id = ?').get(sessionId) : null;

  const sourceDb = new Database(tempSource, { readonly: true, fileMustExist: true });
  // POSIX keeps the inode alive for the open read handle, so the copy can be removed now.
  fs.rmSync(tempDir, { recursive: true, force: true });
  const liveTables = new Set(tableNames(db));
  const restored = {};

  db.pragma('foreign_keys = OFF');
  try {
    db.exec('BEGIN IMMEDIATE');
    try {
      for (const table of inspection.tables) {
        if (!liveTables.has(table)) continue; // a newer snapshot may know tables this build does not
        if (/^sqlite_/i.test(table)) continue; // internal tables (sqlite_sequence) are not user data
        const liveColumns = new Set(db.prepare(`PRAGMA table_info(${quoteIdent(table)})`).all().map((c) => c.name));
        const columns = sourceDb
          .prepare(`PRAGMA table_info(${quoteIdent(table)})`)
          .all()
          .map((c) => c.name)
          .filter((c) => liveColumns.has(c));

        db.prepare(`DELETE FROM ${quoteIdent(table)}`).run();
        if (!columns.length) {
          restored[table] = 0;
          continue;
        }
        const rows = sourceDb.prepare(`SELECT ${columns.map(quoteIdent).join(',')} FROM ${quoteIdent(table)}`).all();
        const insert = db.prepare(
          `INSERT INTO ${quoteIdent(table)} (${columns.map(quoteIdent).join(',')}) VALUES (${columns.map(() => '?').join(',')})`
        );
        for (const row of rows) insert.run(columns.map((c) => row[c]));
        restored[table] = rows.length;
      }
      db.exec('COMMIT');
    } catch (err) {
      try {
        db.exec('ROLLBACK');
      } catch {
        /* transaction already closed */
      }
      throw httpError(409, `The restore was rolled back and your data is unchanged: ${err.message}`);
    }
  } finally {
    db.pragma('foreign_keys = ON');
    sourceDb.close();
  }

  const integrity = String(db.pragma('integrity_check', { simple: true }));
  const foreignKeyViolations = db.pragma('foreign_key_check').length;

  // Founder authority is bound from server configuration, so it survives a snapshot that
  // predates the account. Without this a restore could leave the Founder signed out for good.
  ensureFounderAccount();

  // Keep the acting Founder signed in when the snapshot predates their current session.
  let sessionPreserved = false;
  if (sessionRow) {
    const userExists = db.prepare('SELECT 1 FROM users WHERE id = ?').get(sessionRow.user_id);
    const sessionExists = db.prepare('SELECT 1 FROM sessions WHERE id = ?').get(sessionRow.id);
    if (userExists && !sessionExists) {
      const columns = Object.keys(sessionRow);
      db.prepare(
        `INSERT INTO sessions (${columns.map(quoteIdent).join(',')}) VALUES (${columns.map(() => '?').join(',')})`
      ).run(columns.map((c) => sessionRow[c]));
      sessionPreserved = true;
    }
  }

  audit(
    actorId,
    'backup.restore',
    'backup',
    name,
    { source, safetyBackup: safety.name, rows: Object.values(restored).reduce((a, b) => a + b, 0), integrity, foreignKeyViolations },
    ip
  );

  return {
    restoredFrom: name,
    source,
    safetyBackup: safety.name,
    tables: restored,
    rows: Object.values(restored).reduce((a, b) => a + b, 0),
    integrity,
    foreignKeyViolations,
    sessionPreserved,
  };
}

/* ---------------------------- off-platform archive ---------------------------- */

const CRC_TABLE = (() => {
  const table = new Int32Array(256);
  for (let i = 0; i < 256; i += 1) {
    let c = i;
    for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[i] = c;
  }
  return table;
})();

const crcInit = () => 0xffffffff;
const crcFinal = (state) => (state ^ 0xffffffff) >>> 0;
function crcFeed(state, buffer) {
  let c = state;
  for (let i = 0; i < buffer.length; i += 1) c = CRC_TABLE[(c ^ buffer[i]) & 0xff] ^ (c >>> 8);
  return c >>> 0;
}

function crc32File(file) {
  const fd = fs.openSync(file, 'r');
  const buffer = Buffer.alloc(512 * 1024);
  let state = crcInit();
  let size = 0;
  try {
    let read = 0;
    while ((read = fs.readSync(fd, buffer, 0, buffer.length, null)) > 0) {
      state = crcFeed(state, buffer.subarray(0, read));
      size += read;
    }
  } finally {
    fs.closeSync(fd);
  }
  return { crc: crcFinal(state), size };
}

function dosDateTime(date = new Date()) {
  return {
    time: ((date.getHours() & 0x1f) << 11) | ((date.getMinutes() & 0x3f) << 5) | (Math.floor(date.getSeconds() / 2) & 0x1f),
    date: (((date.getFullYear() - 1980) & 0x7f) << 9) | (((date.getMonth() + 1) & 0x0f) << 5) | (date.getDate() & 0x1f),
  };
}

/**
 * Minimal ZIP writer (stored entries, no compression). Uploaded media is already compressed,
 * so storing keeps the archive fast and avoids a dependency; files are streamed so a large
 * video is never held in memory.
 */
function writeZip(dest, entries) {
  const fd = fs.openSync(dest, 'w');
  const central = [];
  const { time, date } = dosDateTime();
  let offset = 0;
  try {
    for (const entry of entries) {
      const nameBuf = Buffer.from(entry.name, 'utf8');
      let size;
      let crc;
      if (entry.buffer) {
        size = entry.buffer.length;
        crc = crcFinal(crcFeed(crcInit(), entry.buffer));
      } else {
        const result = crc32File(entry.source);
        size = result.size;
        crc = result.crc;
      }
      const local = Buffer.alloc(30);
      local.writeUInt32LE(0x04034b50, 0);
      local.writeUInt16LE(20, 4);
      local.writeUInt16LE(0x0800, 6); // UTF-8 names
      local.writeUInt16LE(0, 8); // stored
      local.writeUInt16LE(time, 10);
      local.writeUInt16LE(date, 12);
      local.writeUInt32LE(crc, 14);
      local.writeUInt32LE(size, 18);
      local.writeUInt32LE(size, 22);
      local.writeUInt16LE(nameBuf.length, 26);
      local.writeUInt16LE(0, 28);
      fs.writeSync(fd, local);
      fs.writeSync(fd, nameBuf);

      if (entry.buffer) {
        fs.writeSync(fd, entry.buffer);
      } else {
        const readFd = fs.openSync(entry.source, 'r');
        const chunk = Buffer.alloc(512 * 1024);
        try {
          let read = 0;
          while ((read = fs.readSync(readFd, chunk, 0, chunk.length, null)) > 0) fs.writeSync(fd, chunk.subarray(0, read));
        } finally {
          fs.closeSync(readFd);
        }
      }

      central.push({ nameBuf, crc, size, offset, time, date });
      offset += 30 + nameBuf.length + size;
    }

    const cdStart = offset;
    let cdSize = 0;
    for (const entry of central) {
      const header = Buffer.alloc(46);
      header.writeUInt32LE(0x02014b50, 0);
      header.writeUInt16LE(20, 4);
      header.writeUInt16LE(20, 6);
      header.writeUInt16LE(0x0800, 8);
      header.writeUInt16LE(0, 10);
      header.writeUInt16LE(entry.time, 12);
      header.writeUInt16LE(entry.date, 14);
      header.writeUInt32LE(entry.crc, 16);
      header.writeUInt32LE(entry.size, 20);
      header.writeUInt32LE(entry.size, 24);
      header.writeUInt16LE(entry.nameBuf.length, 28);
      header.writeUInt16LE(0, 30);
      header.writeUInt16LE(0, 32);
      header.writeUInt16LE(0, 34);
      header.writeUInt16LE(0, 36);
      header.writeUInt32LE(0, 38);
      header.writeUInt32LE(entry.offset, 42);
      fs.writeSync(fd, header);
      fs.writeSync(fd, entry.nameBuf);
      cdSize += 46 + entry.nameBuf.length;
    }

    const eocd = Buffer.alloc(22);
    eocd.writeUInt32LE(0x06054b50, 0);
    eocd.writeUInt16LE(0, 4);
    eocd.writeUInt16LE(0, 6);
    eocd.writeUInt16LE(central.length, 8);
    eocd.writeUInt16LE(central.length, 10);
    eocd.writeUInt32LE(cdSize, 12);
    eocd.writeUInt32LE(cdStart, 16);
    eocd.writeUInt16LE(0, 20);
    fs.writeSync(fd, eocd);
  } finally {
    fs.closeSync(fd);
  }
}

/**
 * Build a downloadable archive: the verified snapshot, every uploaded file and a manifest
 * with restore instructions. This is the only copy that survives a container reset on the
 * Free plan, so the Founder keeps it off-platform.
 */
export function buildArchive({ actorId = null } = {}) {
  const snapshot = createBackup({ reason: 'archive', actorId });
  const stampName = `ash-mesh-export-${stamp()}-${crypto.randomBytes(3).toString('hex')}.zip`;
  const dest = path.join(os.tmpdir(), stampName);

  const uploadFiles = fs.existsSync(UPLOAD_DIR)
    ? fs
        .readdirSync(UPLOAD_DIR)
        .map((file) => path.join(UPLOAD_DIR, file))
        .filter((file) => fs.statSync(file).isFile())
    : [];

  // Per-file checksums make a restore able to prove that every recovered photo, video and
  // document is byte-identical to the copy that was exported.
  const uploadIndex = uploadFiles.map((file) => ({
    name: path.basename(file),
    sizeBytes: fs.statSync(file).size,
    sha256: sha256File(file),
  }));
  const uploadBytes = uploadIndex.reduce((sum, f) => sum + f.sizeBytes, 0);

  const manifest = {
    application: '#ash Mesh',
    format: ARCHIVE_FORMAT,
    exportedAt: now(),
    exportedBy: actorId || null,
    database: {
      file: `database/${snapshot.name}`,
      sha256: snapshot.sha256,
      sizeBytes: snapshot.sizeBytes,
      tableCount: snapshot.tableCount,
      rows: snapshot.rows,
      counts: snapshot.counts,
    },
    uploads: { count: uploadIndex.length, bytes: uploadBytes, directory: 'uploads/', files: uploadIndex },
    restore: [
      '1. Sign in as the Founder and open Profile / Menu -> Data & backups.',
      '2. Choose "Restore from archive (.zip)" and select this file.',
      '3. The archive is validated first: manifest, database integrity, checksums and every file path.',
      '4. A pre-restore safety snapshot is written automatically before anything changes.',
      '5. Database rows and the uploads/ files are restored together; if any step fails, both are rolled back.',
      '6. Keep this archive off-platform: this plan has no persistent disk, so container copies are lost on redeploy.',
    ],
  };

  const entries = [
    { name: 'manifest.json', buffer: Buffer.from(JSON.stringify(manifest, null, 2), 'utf8') },
    { name: `database/${snapshot.name}`, source: path.join(BACKUP_DIR, snapshot.name) },
    ...uploadFiles.map((file) => ({ name: `uploads/${path.basename(file)}`, source: file })),
  ];
  writeZip(dest, entries);

  const sizeBytes = fs.statSync(dest).size;
  audit(actorId, 'backup.archive', 'archive', stampName, { snapshot: snapshot.name, uploads: uploadFiles.length, uploadBytes, sizeBytes }, '');
  return { path: dest, name: stampName, snapshot: snapshot.name, files: entries.length, sizeBytes, uploadBytes, manifest };
}

/* ----------------------- archive validation and restore ----------------------- */

function readAt(fd, buffer, position) {
  let offset = 0;
  while (offset < buffer.length) {
    const read = fs.readSync(fd, buffer, offset, buffer.length - offset, position + offset);
    if (!read) throw httpError(400, 'The archive is truncated.');
    offset += read;
  }
  return buffer;
}

/**
 * Parse a ZIP central directory without trusting it.
 *
 * Only metadata is read here; nothing is written. Entry count, sizes and compression methods
 * are checked so a crafted archive cannot exhaust the container.
 */
function readZipDirectory(file) {
  const stat = fs.statSync(file);
  if (!stat.isFile() || stat.size < 22) throw httpError(400, 'That file is not a readable ZIP archive.');

  const tailLength = Math.min(stat.size, 66 * 1024);
  const fd = fs.openSync(file, 'r');
  let tail;
  try {
    tail = readAt(fd, Buffer.alloc(tailLength), stat.size - tailLength);
  } finally {
    fs.closeSync(fd);
  }

  let eocd = -1;
  for (let i = tail.length - 22; i >= 0; i -= 1) {
    if (tail.readUInt32LE(i) === 0x06054b50) {
      eocd = i;
      break;
    }
  }
  if (eocd < 0) throw httpError(400, 'That file is not a readable ZIP archive.');

  const entryCount = tail.readUInt16LE(eocd + 10);
  const directorySize = tail.readUInt32LE(eocd + 12);
  const directoryOffset = tail.readUInt32LE(eocd + 16);
  if (entryCount === 0xffff || directoryOffset === 0xffffffff) {
    throw httpError(413, 'That ZIP archive is too large to restore on this server.');
  }
  if (entryCount > ARCHIVE_MAX_ENTRIES) {
    throw httpError(413, `The archive contains more than ${ARCHIVE_MAX_ENTRIES} entries.`);
  }
  if (directoryOffset + directorySize > stat.size) throw httpError(400, 'That ZIP archive is corrupt.');

  const directory = Buffer.alloc(directorySize);
  const handle = fs.openSync(file, 'r');
  try {
    readAt(handle, directory, directoryOffset);
  } finally {
    fs.closeSync(handle);
  }

  const entries = [];
  let pointer = 0;
  while (pointer + 46 <= directory.length) {
    if (directory.readUInt32LE(pointer) !== 0x02014b50) throw httpError(400, 'That ZIP archive is corrupt.');
    const flags = directory.readUInt16LE(pointer + 8);
    const method = directory.readUInt16LE(pointer + 10);
    const crc = directory.readUInt32LE(pointer + 16);
    const compSize = directory.readUInt32LE(pointer + 20);
    const uncompSize = directory.readUInt32LE(pointer + 24);
    const nameLength = directory.readUInt16LE(pointer + 28);
    const extraLength = directory.readUInt16LE(pointer + 30);
    const commentLength = directory.readUInt16LE(pointer + 32);
    const localOffset = directory.readUInt32LE(pointer + 42);
    const name = directory.subarray(pointer + 46, pointer + 46 + nameLength).toString('utf8');

    if (flags & 0x1) throw httpError(400, 'Encrypted ZIP archives are not supported.');
    if (compSize === 0xffffffff || uncompSize === 0xffffffff || localOffset === 0xffffffff) {
      throw httpError(413, 'That ZIP archive uses 64-bit entries this server cannot restore.');
    }

    entries.push({ name, method, crc, compSize, uncompSize, localOffset, isDirectory: name.endsWith('/') });
    pointer += 46 + nameLength + extraLength + commentLength;
  }
  if (entries.length !== entryCount) throw httpError(400, 'That ZIP archive is corrupt.');
  return entries;
}

/** Extract one verified entry to `dest`: size, checksum and method are all enforced. */
function extractZipEntry(file, entry, dest) {
  if (entry.method !== 0 && entry.method !== 8) {
    throw httpError(400, `The archive uses an unsupported compression method for ${entry.name}.`);
  }
  if (entry.uncompSize > ARCHIVE_MAX_FILE_BYTES) {
    throw httpError(413, `The archive entry ${entry.name} is larger than this server accepts.`);
  }

  const fd = fs.openSync(file, 'r');
  let start;
  try {
    const header = readAt(fd, Buffer.alloc(30), entry.localOffset);
    if (header.readUInt32LE(0) !== 0x04034b50) throw httpError(400, 'That ZIP archive is corrupt.');
    start = entry.localOffset + 30 + header.readUInt16LE(26) + header.readUInt16LE(28);
  } finally {
    fs.closeSync(fd);
  }

  if (entry.method === 8) {
    if (entry.compSize > ARCHIVE_MAX_INFLATE_BYTES) {
      throw httpError(413, `The archive entry ${entry.name} is too large to decompress safely.`);
    }
    const compressed = Buffer.alloc(entry.compSize);
    const handle = fs.openSync(file, 'r');
    try {
      readAt(handle, compressed, start);
    } finally {
      fs.closeSync(handle);
    }
    let data;
    try {
      data = zlib.inflateRawSync(compressed);
    } catch {
      throw httpError(400, `The archive entry ${entry.name} could not be decompressed.`);
    }
    if (data.length !== entry.uncompSize) throw httpError(400, `The archive entry ${entry.name} has an unexpected size.`);
    if (crcFinal(crcFeed(crcInit(), data)) !== entry.crc) {
      throw httpError(400, `The archive entry ${entry.name} failed its checksum.`);
    }
    fs.writeFileSync(dest, data);
    return { bytes: data.length };
  }

  const source = fs.openSync(file, 'r');
  const target = fs.openSync(dest, 'w');
  const chunk = Buffer.alloc(1024 * 1024);
  let state = crcInit();
  let written = 0;
  try {
    while (written < entry.compSize) {
      const want = Math.min(chunk.length, entry.compSize - written);
      const read = fs.readSync(source, chunk, 0, want, start + written);
      if (!read) throw httpError(400, 'The archive is truncated.');
      state = crcFeed(state, chunk.subarray(0, read));
      fs.writeSync(target, chunk.subarray(0, read));
      written += read;
    }
  } finally {
    fs.closeSync(source);
    fs.closeSync(target);
  }
  if (written !== entry.uncompSize) throw httpError(400, `The archive entry ${entry.name} has an unexpected size.`);
  if (crcFinal(state) !== entry.crc) throw httpError(400, `The archive entry ${entry.name} failed its checksum.`);
  return { bytes: written };
}

/**
 * Read and validate an export archive without changing anything.
 *
 * Rejects unsafe paths, duplicate entries, a missing manifest, a database that is not a healthy
 * #ash Mesh snapshot, and any upload name that is not a bare media filename.
 */
export function inspectArchive(file) {
  if (!file || !fs.existsSync(file)) throw httpError(400, 'No archive was received.');

  const entries = readZipDirectory(file);
  const byName = new Map();
  for (const entry of entries) {
    if (entry.isDirectory) continue;
    const parts = entry.name.split('/');
    if (entry.name.includes('\\') || entry.name.startsWith('/') || parts.includes('..') || entry.name.includes('\u0000')) {
      throw httpError(400, `The archive contains an unsafe path (${entry.name}).`);
    }
    if (byName.has(entry.name)) throw httpError(400, `The archive contains a duplicate entry (${entry.name}).`);
    byName.set(entry.name, entry);
  }

  const manifestEntry = byName.get('manifest.json');
  if (!manifestEntry) throw httpError(400, 'The archive has no manifest.json, so it is not an #ash Mesh export.');
  if (manifestEntry.uncompSize > 4 * 1024 * 1024) throw httpError(400, 'The archive manifest is unexpectedly large.');

  const work = fs.mkdtempSync(path.join(os.tmpdir(), 'ash-archive-inspect-'));
  let manifest;
  try {
    const manifestPath = path.join(work, 'manifest.json');
    extractZipEntry(file, manifestEntry, manifestPath);
    manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  } catch (err) {
    if (err.status) throw err;
    throw httpError(400, `The archive manifest could not be read: ${err.message}`);
  } finally {
    fs.rmSync(work, { recursive: true, force: true });
  }

  if (!manifest || typeof manifest !== 'object' || !String(manifest.format || '').startsWith('ash-mesh-export/')) {
    throw httpError(400, 'That ZIP is not an #ash Mesh export archive.');
  }

  const databaseEntries = [...byName.values()].filter((entry) => /^database\/[^/]+\.db$/.test(entry.name));
  if (databaseEntries.length !== 1) {
    throw httpError(400, 'The archive must contain exactly one database/<snapshot>.db file.');
  }

  const uploads = [];
  for (const entry of byName.values()) {
    if (!entry.name.startsWith('uploads/')) continue;
    const name = safeUploadName(entry.name.slice('uploads/'.length));
    if (!name) throw httpError(400, `The archive contains an unsafe media filename (${entry.name}).`);
    uploads.push({ name, entry });
  }

  return { manifest, database: databaseEntries[0], uploads, format: String(manifest.format) };
}

/** Copy staged media into UPLOAD_DIR, journalling every file so a failure can be undone. */
function applyMediaFiles(stagingUploads, workDir) {
  const journal = { rollbackDir: path.join(workDir, 'media-rollback'), applied: [], replaced: [], created: [] };
  fs.mkdirSync(journal.rollbackDir, { recursive: true });
  fs.mkdirSync(UPLOAD_DIR, { recursive: true });

  const names = fs
    .readdirSync(stagingUploads)
    .filter((name) => fs.statSync(path.join(stagingUploads, name)).isFile());

  for (const name of names) {
    const source = path.join(stagingUploads, name);
    const target = path.join(UPLOAD_DIR, name);
    const existed = fs.existsSync(target);
    if (existed) {
      // Keep the current bytes: if the database step fails, the original media comes back.
      fs.copyFileSync(target, path.join(journal.rollbackDir, name));
      journal.replaced.push(name);
    }
    const temp = path.join(UPLOAD_DIR, `.restore-${crypto.randomBytes(8).toString('hex')}.tmp`);
    fs.copyFileSync(source, temp);
    fs.renameSync(temp, target);
    journal.applied.push(name);
    if (!existed) journal.created.push(name);
  }
  return journal;
}

/** Undo applyMediaFiles(): restore overwritten bytes and remove files the restore created. */
function rollbackMedia(journal) {
  const result = { restored: [], removed: [], failed: [] };
  for (const name of journal.applied.slice().reverse()) {
    const target = path.join(UPLOAD_DIR, name);
    try {
      if (journal.replaced.includes(name)) {
        fs.copyFileSync(path.join(journal.rollbackDir, name), target);
        result.restored.push(name);
      } else {
        fs.rmSync(target, { force: true });
        result.removed.push(name);
      }
    } catch (err) {
      result.failed.push(`${name}: ${err.message}`);
    }
  }
  for (const leftover of fs.existsSync(UPLOAD_DIR) ? fs.readdirSync(UPLOAD_DIR) : []) {
    if (leftover.startsWith('.restore-') && leftover.endsWith('.tmp')) {
      fs.rmSync(path.join(UPLOAD_DIR, leftover), { force: true });
    }
  }
  return result;
}

/**
 * Restore a downloaded export archive: database rows AND uploaded media.
 *
 * Order matters. Everything is extracted and verified in a staging directory first, so a bad
 * archive is refused before a single live byte changes. A pre-restore safety snapshot is then
 * written, media is applied with a journal, and only then is the database restored. If any
 * later step fails, the media journal is replayed and the database is rolled back to the
 * safety snapshot, so the live state is left as it was.
 */
export function restoreArchive(zipPath, { actorId = null, sessionId = null, ip = '', filename = '' } = {}) {
  const plan = inspectArchive(zipPath);
  const work = fs.mkdtempSync(path.join(os.tmpdir(), 'ash-archive-restore-'));

  try {
    const stagedDb = path.join(work, 'restore.db');
    extractZipEntry(zipPath, plan.database, stagedDb);

    const head = Buffer.alloc(16);
    const handle = fs.openSync(stagedDb, 'r');
    try {
      fs.readSync(handle, head, 0, 16, 0);
    } finally {
      fs.closeSync(handle);
    }
    if (head.toString('latin1') !== 'SQLite format 3\u0000') {
      throw httpError(400, 'The archive does not contain a SQLite database.');
    }

    const inspection = inspectDatabaseFile(stagedDb);
    if (inspection.integrity !== 'ok') throw httpError(400, 'The archived database failed its integrity check, so nothing was restored.');
    if (!inspection.tables.includes('users')) throw httpError(400, 'The archived database is not an #ash Mesh database (no accounts table).');

    const databaseSha = sha256File(stagedDb);
    const recordedSha = plan.manifest?.database?.sha256;
    if (recordedSha && recordedSha !== databaseSha) {
      throw httpError(400, 'The archived database does not match the checksum recorded in its manifest.');
    }

    // Stage the media and prove every file matches the manifest before touching live media.
    const stagedUploads = path.join(work, 'uploads');
    fs.mkdirSync(stagedUploads, { recursive: true });
    const manifestFiles = new Map(
      (Array.isArray(plan.manifest?.uploads?.files) ? plan.manifest.uploads.files : [])
        .filter((file) => file && typeof file.name === 'string')
        .map((file) => [file.name, file])
    );

    const expected = [];
    let mediaBytes = 0;
    for (const item of plan.uploads) {
      mediaBytes += item.entry.uncompSize;
      if (mediaBytes > ARCHIVE_MAX_TOTAL_BYTES) {
        throw httpError(413, 'The archive media is larger than this server accepts.');
      }
      const dest = path.join(stagedUploads, item.name);
      extractZipEntry(zipPath, item.entry, dest);
      const stat = fs.statSync(dest);
      const recorded = manifestFiles.get(item.name);
      if (recorded?.sizeBytes != null && Number(recorded.sizeBytes) !== stat.size) {
        throw httpError(400, `The archive copy of ${item.name} does not match its manifest size.`);
      }
      const digest = sha256File(dest);
      if (recorded?.sha256 && recorded.sha256 !== digest) {
        throw httpError(400, `The archive copy of ${item.name} does not match its manifest checksum.`);
      }
      expected.push({ name: item.name, sizeBytes: stat.size, sha256: digest });
    }

    // Nothing above this line changed live state. From here on, everything is reversible.
    const safety = createBackup({ reason: 'pre-archive-restore', actorId });
    const journal = applyMediaFiles(stagedUploads, work);
    let restore = null;

    try {
      const adopted = adoptUploadedBackup(stagedDb, { actorId });
      restore = restoreBackup(adopted.name, { actorId, sessionId, ip, source: 'archive' });

      for (const file of expected) {
        const target = path.join(UPLOAD_DIR, file.name);
        if (!fs.existsSync(target) || fs.statSync(target).size !== file.sizeBytes) {
          throw new Error(`${file.name} is missing after the media restore`);
        }
        if (sha256File(target) !== file.sha256) {
          throw new Error(`${file.name} does not match its checksum after the media restore`);
        }
      }
    } catch (err) {
      const mediaRollback = rollbackMedia(journal);
      let databaseRollback = 'not needed';
      if (restore) {
        try {
          const rolled = restoreBackup(safety.name, { actorId, ip, source: 'archive-rollback' });
          databaseRollback = rolled.restoredFrom;
        } catch (rollbackError) {
          databaseRollback = `failed: ${rollbackError.message}`;
        }
      }
      audit(actorId, 'backup.restore-archive-failed', 'archive', filename || plan.database.name, {
        error: err.message,
        mediaRollback,
        databaseRollback,
        safetyBackup: safety.name,
      }, ip);
      throw httpError(
        409,
        `The archive restore was rolled back and your data is unchanged: ${err.message}. Media restored from the journal: ${mediaRollback.restored.length}, removed: ${mediaRollback.removed.length}.`
      );
    }

    audit(actorId, 'backup.restore-archive', 'archive', filename || plan.database.name, {
      database: plan.database.name,
      databaseSha256: databaseSha,
      mediaFiles: expected.length,
      mediaBytes,
      rows: restore.rows,
      integrity: restore.integrity,
      safetyBackup: safety.name,
    }, ip);

    return {
      ...restore,
      source: 'archive',
      archive: {
        name: filename || null,
        format: plan.format,
        database: plan.database.name,
        databaseSha256: databaseSha,
        integrity: inspection.integrity,
        rows: inspection.rows,
        mediaFiles: expected.length,
        mediaBytes,
      },
      media: {
        restored: expected.length,
        created: journal.created.length,
        overwritten: journal.replaced.length,
        bytes: mediaBytes,
        directory: path.relative(DATA_DIR, UPLOAD_DIR) || 'uploads',
      },
      archiveSafetyBackup: safety.name,
    };
  } finally {
    fs.rmSync(work, { recursive: true, force: true });
  }
}

/* -------------------------------- scheduler ------------------------------- */

let timer = null;

export function startBackupScheduler() {
  if (timer || !BACKUP_SCHEDULER_ENABLED) return timer;
  const run = () => {
    try {
      const created = createBackup({ reason: 'scheduled' });
      console.log(`[#ash Mesh] Backup ${created.name} written (${created.rows} rows, ${created.sizeBytes} bytes).`);
    } catch (err) {
      console.error('[#ash Mesh] Scheduled backup failed:', err.message);
    }
  };
  timer = setInterval(run, BACKUP_INTERVAL_MINUTES * 60 * 1000);
  timer.unref();
  const first = setTimeout(run, BACKUP_INITIAL_DELAY_MS);
  first.unref();
  return timer;
}

export function stopBackupScheduler() {
  if (timer) clearInterval(timer);
  timer = null;
}

/* --------------------------------- status --------------------------------- */

export function backupStatus() {
  const backups = listBackups();
  const latest = backups[0] || null;
  const ageMinutes = latest ? Math.max(0, Math.round((Date.now() - new Date(latest.createdAt).getTime()) / 60000)) : null;
  const staleAfterMinutes = BACKUP_INTERVAL_MINUTES * 2;

  const warnings = [];
  if (!latest) warnings.push('No snapshot exists yet. Create one now.');
  else if (ageMinutes > staleAfterMinutes) warnings.push(`The newest snapshot is ${ageMinutes} minutes old.`);
  warnings.push(
    'This plan has no persistent disk: snapshots stored in the container are lost on redeploy. Download an archive and keep it off-platform.'
  );

  return {
    policy: {
      retention: BACKUP_RETENTION,
      intervalMinutes: BACKUP_INTERVAL_MINUTES,
      schedulerEnabled: BACKUP_SCHEDULER_ENABLED,
      directory: path.relative(DATA_DIR, BACKUP_DIR) || '.',
      durableStorage: false,
      includesUploadsInArchive: true,
      archiveRestoreIncludesUploads: true,
    },
    count: backups.length,
    latest,
    latestAgeMinutes: ageMinutes,
    uploadsBytes: fs.existsSync(UPLOAD_DIR)
      ? fs.readdirSync(UPLOAD_DIR).reduce((sum, file) => {
          try {
            return sum + fs.statSync(path.join(UPLOAD_DIR, file)).size;
          } catch {
            return sum;
          }
        }, 0)
      : 0,
    warnings,
  };
}

