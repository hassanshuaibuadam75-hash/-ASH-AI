export function seedOfficialPosts() {
  const account = aiAccount();
  if (!account) return { seeded: 0 };
  const existing = db.prepare('SELECT COUNT(*) c FROM posts WHERE author_id = ?').get(account.id).c;
  if (existing > 0) return { seeded: 0, existing };

  const insert = db.prepare(
    `INSERT INTO posts (id, author_id, body, kind, audience, ai_generated, category, created_at, updated_at)
     VALUES (?,?,?,?,?,?,?,?,?)`
  );
  let seeded = 0;
  STARTER_POSTS.forEach((post, index) => {
    try {
      const ts = new Date(Date.now() - index * 3600 * 1000).toISOString();
      insert.run(uid('post_'), account.id, post.body, 'text', 'public', 1, post.category, ts, ts);
      seeded += 1;
    } catch {
      /* if the category column is unavailable, skip rather than break boot */
    }
  });
  return { seeded };
}

// Automatic seeding only for a real deployment, never while tests run.
if (process.env.NODE_ENV === 'production' && process.env.ASH_AI_AUTOSEED !== 'off') {
  try {
    seedOfficialPosts();
  } catch {
    /* never block server boot for starter content */
  }
}

