// #ash Mesh — the official #ash AI account.
//
// One clearly labelled, verified AI identity (@ashai). It can publish educational content,
// technology tips, platform announcements, Islamic reminders and Kano/Nigerian heritage
// notes — always marked as AI-generated, never impersonating a person.
//
// Publishing requires staff permission, and the AI never invents a success: the response
// reflects what was actually written to the database.
import express from 'express';
import { db, uid, now } from './db.js';
import { requireAuth, rateLimit, clean, badRequest } from './lib.js';

export const AI_ACCOUNT = { username: 'ashai', email: 'ai@ashmesh.com', displayName: '#ash AI' };
export const AI_DISCLOSURE = 'Generated by #ash AI. AI output can be wrong — verify anything important.';

const router = express.Router();

export const CATEGORIES = {
  education: { label: 'Educational content' },
  tech: { label: 'Technology tip' },
  announcement: { label: 'Platform announcement' },
  islamic: { label: 'Islamic reminder' },
  heritage: { label: 'Kano & Nigerian heritage' },
};

function isStaff(user) {
  if (!user) return false;
  if (user.is_founder === 1 || user.role === 'founder' || user.role === 'admin' || user.role === 'moderator') return true;
  try {
    return JSON.parse(user.permissions || '[]').includes('ai.publish');
  } catch {
    return false;
  }
}

function aiAccount() {
  return db.prepare('SELECT * FROM users WHERE username = ?').get(AI_ACCOUNT.username);
}

function aiPostView(row, viewerId) {
  if (!row) return null;
  const author = aiAccount();
  return {
    id: row.id,
    body: row.body,
    category: row.category || 'announcement',
    audience: row.audience,
    aiGenerated: true,
    disclosure: AI_DISCLOSURE,
    createdAt: row.created_at,
    author: {
      id: author.id,
      username: author.username,
      fullName: author.full_name,
      avatarUrl: author.avatar_url || null,
      isAi: true,
      verified: true,
    },
    isOwner: viewerId === author.id,
  };
}

/* ------------------------------- read side -------------------------------- */

// The official account and its latest posts. Available to any signed-in member so the
// feed and the AI page can show real published content.
router.get('/ai/official', requireAuth, (_req, res) => {
  const account = aiAccount();
  if (!account) {
    return res.json({ account: null, posts: [], categories: CATEGORIES, disclosure: AI_DISCLOSURE });
  }
  const posts = db
    .prepare("SELECT * FROM posts WHERE author_id = ? AND (moderation_status IS NULL OR moderation_status = 'visible') ORDER BY created_at DESC LIMIT 10")
    .all(account.id)
    .map((row) => aiPostView(row, _req.user.id));

  res.json({
    account: {
      id: account.id,
      username: account.username,
      fullName: account.full_name,
      avatarUrl: account.avatar_url || null,
      bio: account.bio || '',
      isAi: true,
      verified: true,
    },
    posts,
    categories: CATEGORIES,
    disclosure: AI_DISCLOSURE,
    canPublish: isStaff(_req.user),
  });
});

/* ------------------------------ publish side ------------------------------ */

// Publish as the official account. The body must be supplied by a human operator (or
// drafted in the AI chat and pasted in), so nothing is generated silently and the stored
// text is exactly what a person approved.
router.post(
  '/ai/official/publish',
  requireAuth,
  rateLimit({ name: 'ai_publish', limit: 30, windowMs: 60 * 60 * 1000 }),
  (req, res) => {
    if (!isStaff(req.user)) {
      return res.status(403).json({ error: 'forbidden', message: 'Only authorised staff can publish as #ash AI.' });
    }
    const account = aiAccount();
    if (!account) {
      return res.status(503).json({ error: 'ai_account_missing', message: 'The #ash AI account is not ready yet.' });
    }

    const category = clean(req.body.category, 30) || 'announcement';
    if (!CATEGORIES[category]) return badRequest(res, 'Choose a supported content category.');

    const body = clean(req.body.body, 4000);
    if (!body) return badRequest(res, 'Write the content to publish.');

    const id = uid('post_');
    const ts = now();
    db.prepare(
      `INSERT INTO posts (id, author_id, body, kind, audience, ai_generated, created_at, updated_at)
       VALUES (?,?,?,?,?,?,?,?)`
    ).run(id, account.id, body, 'text', 'public', 1, ts, ts);

    const row = db.prepare('SELECT * FROM posts WHERE id = ?').get(id);
    return res.status(201).json({ post: aiPostView(row, req.user.id), published: true });
  }
);

// Staff-only: remove an official post (soft, keeps the record for the audit trail).
router.delete('/ai/official/posts/:id', requireAuth, (req, res) => {
  if (!isStaff(req.user)) {
    return res.status(403).json({ error: 'forbidden', message: 'Only authorised staff can unpublish.' });
  }
  const account = aiAccount();
  const row = db.prepare('SELECT * FROM posts WHERE id = ? AND author_id = ?').get(req.params.id, account?.id);
  if (!row) return res.status(404).json({ error: 'not_found', message: 'Official post not found.' });
  db.prepare("UPDATE posts SET moderation_status = 'removed', updated_at = ? WHERE id = ?").run(now(), row.id);
  res.json({ unpublished: true, id: row.id });
});

